/*!
\brief Overloaded.
\param s Stream.
\param disctile The disc tile.
*/
std::ostream& operator<<(std::ostream& s, const DiscTile& disctile)
{
    s << "DiscTile(" << disctile.s << ", " << disctile.r << ") // n = " << disctile.p.size();
    for (const Vector2& v : disctile.p)
    {
        s << v << std::endl;
    }
    return s;
}


